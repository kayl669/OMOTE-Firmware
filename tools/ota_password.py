# Compiles the environment variable OTA_PASSWORD into the firmware. It protects OTA updates and telnet.
import os

Import("env")

password = os.environ.get("OTA_PASSWORD", "")
if not password:
    print("WARNING: environment variable OTA_PASSWORD is not set. OTA updates and telnet will be disabled.")

# The password is written to a generated header file, which is included by src/secrets.h. Passing it as a
# compiler option instead would alter some special characters, and show the password in verbose build logs.
directory = os.path.join(env.subst("$PROJECT_BUILD_DIR"), env.subst("$PIOENV"), "generated")
header = os.path.join(directory, "ota_password.h")
# every byte is written as an octal escape sequence, so that any character is possible
escaped = "".join("\\%03o" % byte for byte in password.encode("utf-8"))
content = '// generated by tools/ota_password.py\n#define OTA_PASSWORD "%s"\n' % escaped

os.makedirs(directory, exist_ok=True)
with open(header, "w", encoding="ascii") as file:
    file.write(content)

env.Append(CPPPATH=[directory])
